using Invoicing.Domain.Invoices;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Invoicing.Infrastructure.Data.Invoices;

internal class InvoiceConfiguration : IEntityTypeConfiguration<Invoice>
{
    public void Configure(EntityTypeBuilder<Invoice> builder)
    {
        builder.HasMany(i => i.Payments)
            .WithOne()
            .HasForeignKey("InvoiceId");

        builder.Navigation(i => i.Payments)
            .UsePropertyAccessMode(PropertyAccessMode.Field);

        builder.HasMany(i => i.Items)
            .WithOne()
            .HasForeignKey("InvoiceId");

        builder.Navigation(i => i.Items)
            .UsePropertyAccessMode(PropertyAccessMode.Field);
    }
}

internal class InvoiceItemConfiguration : IEntityTypeConfiguration<InvoiceItem>
{
    public void Configure(EntityTypeBuilder<InvoiceItem> builder)
    {
        // Ids are generated by the Domain.
        builder.Property(i => i.Id).ValueGeneratedNever();
    }
}

internal class PaymentConfiguration : IEntityTypeConfiguration<Payment>
{
    public void Configure(EntityTypeBuilder<Payment> builder)
    {
        // Ids are generated by the Domain, so a payment added to a tracked invoice must be inserted.
        builder.Property(p => p.Id).ValueGeneratedNever();

        // Not enforced by the InMemory provider; uniqueness is also checked by the use case.
        builder.HasIndex(p => p.Reference).IsUnique();
    }
}
